-- 036_override_write_order.sql
-- Founder assessment overrides must apply in a deterministic last-writer-wins order. `decided_at`
-- defaults to now(), which is identical for every statement that shares one transaction, so two
-- overrides recorded in the same instant were previously broken by their random uuid (id DESC):
-- a coin toss that could apply an earlier 'set' over a later 'clear' and leave the stale value in
-- force. This adds an insert-ordered sequence as the deterministic tie-breaker — a higher value is
-- a later write and therefore wins. Additive: no existing column, constraint or row is altered, and
-- every statement is safe to re-run.

ALTER TABLE prospect_assessment_overrides
  ADD COLUMN IF NOT EXISTS write_seq bigint GENERATED BY DEFAULT AS IDENTITY;

CREATE INDEX IF NOT EXISTS prospect_assessment_overrides_write_order_idx
  ON prospect_assessment_overrides (prospect_id, field_name, decided_at DESC, write_seq DESC);
